#!/usr/bin/env python3
"""Extract the single production call expression

    ModelListProviderRegistry.fetchModels(...)

from a `ProviderRepository.kt` source tree and emit a compilable driver whose
RECORDING fake registry captures the 5th argument (`context`).

Design notes (why extraction instead of hand-written probe source):

* The behaviour under test is *literally one argument list*.  Copy-pasting the
  line into the harness would prove nothing about the production file — the
  harness would keep passing after the production line regressed.  Extracting
  the real text means the harness红/绿 follows the real source.
* Fail-closed: a moved / renamed / duplicated / re-commented call site makes
  the extractor abort with `EXTRACT_FAIL` (exit 2) instead of emitting a
  driver that compiles against a stale assumption and reports a false PASS.

Usage:
    python3 extract.py --source <ProviderRepository.kt> --out <dir>
"""

import argparse
import os
import sys

ANCHOR = "ModelListProviderRegistry.fetchModels("

DRIVER_TEMPLATE = """// GENERATED by probe/jvm/extract.py from:
//   {source}
// Do not edit — regenerate instead.
package probe

object ModelListProviderRegistry {{
    var called = false
    var lastContext: Any? = null
    var lastForceRefresh: Boolean? = null

    // Signature copied from the production
    // `data/repository/ModelListProviderRegistry.fetchModels` (5th parameter
    // `context` is nullable with a `null` default — which is exactly the
    // shape that let the production call site silently drop it).
    suspend fun fetchModels(
        instance: Any?,
        apiKey: String?,
        thirdParty: Boolean,
        forceRefresh: Boolean = false,
        context: Any? = null,
    ): List<Any> {{
        called = true
        lastContext = context
        lastForceRefresh = forceRefresh
        return emptyList()
    }}
}}

val SENTINEL_CONTEXT: Any = Any()

private val instance: Any? = Any()
private val context: Any? = SENTINEL_CONTEXT
private val apiKey: String? = "sk-probe"
private val isThirdParty: Boolean = false
private val forceRefresh: Boolean = true

suspend fun driveExtracted(): Any? {{
    ModelListProviderRegistry.called = false
    ModelListProviderRegistry.lastContext = null
    ModelListProviderRegistry.lastForceRefresh = null
    // ---- BEGIN extracted expression ----
    {expr}
    // ---- END extracted expression ----
    return ModelListProviderRegistry.lastContext
}}

suspend fun driveExtractedForceRefresh(): Boolean? {{
    driveExtracted()
    return ModelListProviderRegistry.lastForceRefresh
}}
"""


def extract(src: str) -> str:
    first = src.find(ANCHOR)
    if first < 0:
        raise SystemExit("EXTRACT_FAIL: anchor %r not found" % ANCHOR)
    if src.find(ANCHOR, first + 1) >= 0:
        raise SystemExit(
            "EXTRACT_FAIL: anchor %r appears more than once — the 'sole call "
            "site' premise no longer holds, refusing to guess" % ANCHOR
        )
    i = first + len(ANCHOR)
    depth = 1
    j = i
    while j < len(src) and depth > 0:
        c = src[j]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        j += 1
    if depth != 0:
        raise SystemExit("EXTRACT_FAIL: unbalanced parentheses at the call site")
    text = src[first:j]
    if not text.endswith(")"):
        raise SystemExit("EXTRACT_FAIL: extracted text does not end with ')'")
    for line in text.splitlines():
        if "//" in line:
            raise SystemExit(
                "EXTRACT_FAIL: extracted expression carries a line comment — "
                "it would swallow the generated terminator"
            )
    if text.count("\n") > 0 and not text.rstrip().endswith(")"):
        raise SystemExit("EXTRACT_FAIL: multi-line extraction did not terminate cleanly")
    return text


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.source, "r", encoding="utf-8") as fh:
        src = fh.read()

    expr = extract(src)
    os.makedirs(args.out, exist_ok=True)
    dest = os.path.join(args.out, "Generated.kt")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write(DRIVER_TEMPLATE.format(source=args.source, expr=expr))
    print("EXTRACT_OK")
    print("EXTRACTED=%s" % expr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
